/**
 * Typical MF configurations only need remote and host configurations
 * that need to be authored:
 *
 * 1. Host build time — when the host app is being compiled
 * 2. Remote build time — when the remote extension is being compiled
 *
 * The host and remote are two different sides of the contract. The host consumes code provided by the remote (and, via shared modules, vice-versa). The mechanisms to do this are mostly configured at build-time. The host needs to know *which* remotes to load. This is not known ahead of time, so it is configured at runtime.
 *
 * With SSR, the Vite MF build plugin does not create a global Module Federation runtime that we can use to register remotes. For this reason, we do not use the Module Federation Vite plugin on the host. Instead, we set up a runtime ourselves for simplicity.
 */
import pkg from './package.json' with { type: 'json' };
import { writeFile, readFile, mkdir, access } from 'node:fs/promises';
import { dirname, join } from 'node:path';

async function findPackageVersion(name) {
  const url = new URL(import.meta.resolve(name));
  if (url.protocol !== 'file:') {
    throw new Error(`Bad protocol ${url.protocol}`);
  }

  let path = url.pathname;

  // Find the package.json of the package
  while (true) {
    const oldPath = path;
    path = dirname(path);

    // Stop when we don't make progress
    if (path === oldPath) {
      throw new Error(`Expected to find package.json for ${name}, but found ${data.name}`);
    }
    const packagePath = join(path, 'package.json');
    try {
      await access(packagePath);
    } catch {
      continue;
    }

    const data = JSON.parse(await readFile(packagePath, { encoding: 'utf-8' }));
    return data.version;
  }
}

const hostRuntimeSharedLines = await Promise.all(
  Object.entries(pkg.peerDependencies).map(
    async ([name, constraint]) => `"${name}": {
    version: "${await findPackageVersion(name)}",
    get: () => import("${name}").then(mod => () => mod),
    shareConfig: { singleton: true, requiredVersion: "${constraint}" },
},`,
  ),
);
const hostRuntimeSharedBody = '{\n' + hostRuntimeSharedLines.join('\n') + '}';

const moduleBody = `
// AUTOGENERATED — do not manually edit
import type {
  ShareArgs ,
} from '@module-federation/runtime-core/types';
import type {
  ModuleFederationOptions
} from '@module-federation/vite'
import type { NodeRenderers } from '@myst-theme/providers';

/**
 * Shared module definitions for use by a Module Federation host
 */
export const HOST_RUNTIME_SHARED: Record<string, ShareArgs> = ${hostRuntimeSharedBody};


export const SHARED_PACKAGES = Array.from(Object.keys(HOST_RUNTIME_SHARED));


export type ThemeExtensionV1 = {
    v1: {
      renderers?: NodeRenderers;
    }
};
export type ThemeExtension = ThemeExtensionV1;

export type PackageJSON = {
  dependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
};

/**
 * Build shared module definitions for a Module Federation (vite) remote
 */
export function buildRemoteShared(pkg: PackageJSON): Required<ModuleFederationOptions['shared']> {
    const dependencies = {...(pkg.dependencies ?? {}), ...(pkg.peerDependencies ?? {})};
    // Ensure core dependencies are host provided
    const entries = (
        SHARED_PACKAGES.filter(name => name in dependencies).map(name => [
          name, { singleton: true, import: false, requiredVersion: dependencies[name].replace(/^~/, '^')}
        ])
    )
    // TODO allow extensions to provide their own dependencies
    return Object.fromEntries(entries)
}
`;

await mkdir('src', { recursive: true });
await writeFile('src/index.ts', moduleBody);
